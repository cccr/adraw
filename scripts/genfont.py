#!/usr/bin/env python3
"""Regenerate pkg/font/data_*.go from Hershey .jhf files.

    python3 scripts/genfont.py path/to/hershey-fonts   # e.g. kamalmostafa/hershey-fonts

Each .jhf line is one glyph (ASCII 32..126, in order). We keep everything after
the 8-character id/count prefix verbatim: the left and right bearing characters,
then the coordinate pairs, with " R" as pen-up. pkg/font parses it at start-up.
"""
import json
import sys
from pathlib import Path

FONTS = [  # (Go identifier, font name, source file)
    ("simplex", "simplex", "futural.jhf"),
    ("roman", "roman", "timesr.jhf"),
    ("script", "script", "scripts.jhf"),
    ("gothic", "gothic", "gothiceng.jhf"),
    ("duplex", "duplex", "rowmand.jhf"),
    ("triplex", "triplex", "rowmant.jhf"),
    ("cursive", "cursive", "scriptc.jhf"),
    ("italic", "italic", "timesi.jhf"),
    ("bolditalic", "bolditalic", "timesib.jhf"),
    ("fraktur", "fraktur", "gothicger.jhf"),
    ("chancery", "chancery", "gothicita.jhf"),
]

HEADER = """// Code generated by scripts/genfont.py from {src}; DO NOT EDIT.

package font

// Hershey Fonts: originally created by Dr. A. V. Hershey while working at the
// U. S. National Bureau of Standards. The format of the font data was
// originally created by James Hurt, Cognition, Inc., 900 Technology Park Drive,
// Billerica, MA 01821 (mit-eddie!ci-dandelion!hurt). Copyright 1967 Dr. A. V.
// Hershey, James Hurt. May be used by anyone for any purpose provided these
// acknowledgements are distributed with the font data.

var raw{ident} = [95]string{{
"""


def main():
    src = Path(sys.argv[1])
    out = Path(__file__).resolve().parent.parent / "pkg" / "font"
    for ident, _, fname in FONTS:
        lines = (src / fname).read_text().splitlines()
        glyphs = [l[8:] for l in lines if l.strip()][:95]  # the 96th is a block glyph
        assert len(glyphs) == 95, (fname, len(glyphs))
        body = "".join("\t%s,\n" % json.dumps(g) for g in glyphs)
        (out / ("data_%s.go" % ident)).write_text(
            HEADER.format(src=fname, ident=ident.capitalize()) + body + "}\n")


main()
